// Rewrites flutter/CATALOG.md from the pubspecs of this engine and of the
// sibling repositories, so the package list and its consumers cannot drift.
//
//   dart tool/gen_catalog.dart
import 'dart:io';

const layers = [
  'foundation',
  'core',
  'services',
  'components',
  'features',
  'desktop',
];

final _name = RegExp(r'^name:\s*(\S+)', multiLine: true);
final _description = RegExp(r'^description:\s*(.+)$', multiLine: true);
final _dependencyName = RegExp(r'^  ([a-zA-Z_]\w*):');

void main() {
  final engine = Directory.fromUri(Platform.script.resolve('../')).absolute;
  final packages = <String, _Package>{};
  for (final layer in layers) {
    final folder = Directory('${engine.path}flutter/$layer');
    for (final entry in folder.listSync().whereType<Directory>()) {
      final file = File('${entry.path}/pubspec.yaml');
      if (!file.existsSync()) continue;
      final package = _Package.read(file, layer);
      packages[package.name] = package;
    }
  }

  final consumers = <String, Set<String>>{};
  for (final pubspec in _siblingPubspecs(engine)) {
    final text = pubspec.$2.readAsStringSync();
    final label = pubspec.$1;
    for (final dependency in _dependencies(text)) {
      if (packages.containsKey(dependency)) {
        (consumers[dependency] ??= {}).add(label);
      }
    }
  }

  for (final package in packages.values) {
    for (final dependency in _dependencies(package.text)) {
      if (packages.containsKey(dependency)) {
        (consumers[dependency] ??= {}).add(
          package.name.replaceFirst('shipglows_', ''),
        );
      }
    }
  }

  final out = StringBuffer()
    ..writeln('# Catalog')
    ..writeln()
    ..writeln('Generated by `dart tool/gen_catalog.dart`. Do not edit.')
    ..writeln()
    ..writeln('${packages.length} packages. See the layers in the '
        '[README](../README.md).');
  for (final layer in layers) {
    final inLayer =
        packages.values.where((package) => package.layer == layer).toList()
          ..sort((a, b) => a.name.compareTo(b.name));
    out
      ..writeln()
      ..writeln('## $layer')
      ..writeln()
      ..writeln('| Package | Role | Uses | Used by |')
      ..writeln('| --- | --- | --- | --- |');
    for (final package in inLayer) {
      final uses =
          _dependencies(package.text)
              .where(packages.containsKey)
              .map((name) => name.replaceFirst('shipglows_', ''))
              .toList()
            ..sort();
      final users = (consumers[package.name] ?? const <String>{}).toList()
        ..sort();
      out.writeln(
        '| [`${package.name}`]($layer/${package.name}/README.md) '
        '| ${package.description} '
        '| ${uses.join(', ')} '
        '| ${users.isEmpty ? 'none' : users.join(', ')} |',
      );
    }
  }
  File('${engine.path}flutter/CATALOG.md').writeAsStringSync(out.toString());
  stdout.writeln('flutter/CATALOG.md: ${packages.length} packages.');
}

class _Package {
  _Package(this.name, this.description, this.layer, this.text);

  factory _Package.read(File file, String layer) {
    final text = file.readAsStringSync();
    return _Package(
      _name.firstMatch(text)!.group(1)!,
      _description.firstMatch(text)?.group(1)?.trim() ?? '',
      layer,
      text,
    );
  }

  final String name;
  final String description;
  final String layer;
  final String text;
}

Iterable<String> _dependencies(String pubspec) sync* {
  var inside = false;
  for (final line in pubspec.split(RegExp(r'\r?\n'))) {
    if (RegExp(r'^dependencies:\s*$').hasMatch(line)) {
      inside = true;
    } else if (RegExp(r'^\S').hasMatch(line)) {
      inside = false;
    } else if (inside) {
      final match = _dependencyName.firstMatch(line);
      if (match != null) yield match.group(1)!;
    }
  }
}

/// Pubspecs of the sibling repositories, labelled by their repository. The
/// usual places only: `pubspec.yaml`, `app/` and `packages/*`.
Iterable<(String, File)> _siblingPubspecs(Directory engine) sync* {
  final engineName = engine.uri.pathSegments.lastWhere((s) => s.isNotEmpty);
  for (final repo in engine.parent.listSync().whereType<Directory>()) {
    final name = repo.uri.pathSegments.lastWhere((s) => s.isNotEmpty);
    if (name == engineName || name.startsWith('.') || name.startsWith('_')) {
      continue;
    }
    if (name == 'worktrees' || name == 'wt-windows' || name == 'node_modules') {
      continue;
    }
    final candidates = <File>[
      File('${repo.path}/pubspec.yaml'),
      File('${repo.path}/app/pubspec.yaml'),
    ];
    final packages = Directory('${repo.path}/packages');
    if (packages.existsSync()) {
      for (final package in packages.listSync().whereType<Directory>()) {
        candidates.add(File('${package.path}/pubspec.yaml'));
      }
    }
    for (final file in candidates) {
      if (file.existsSync()) yield (name.replaceFirst('shipglows-', ''), file);
    }
  }
}
